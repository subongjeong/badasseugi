// 어절 규칙만으로는 안 나오는 발음(ㄴ 첨가, 사잇소리)은 직접 고친다
const FIX = { '담요도': '담뇨도', '엄지손가락': '엄지손까락', '줄넘기를': '줄럼끼를' };

const sql = [];
for (const [lv, [title, lines]] of Object.entries(LEVELS)) {
  const items = lines.map(t => {
    let sp = globalThis.Pron.sentence(t).split(' ');
    const fixed = strip(t).split(' ').some(w => FIX[w]);
    if (fixed) sp = strip(t).split(' ').map((w, i) => FIX[w] || sp[i]);
    const it = fixed ? makeItem(t, sp.join(' ')) : makeItem(t);
    const words = strip(t).split(' ');
    for (const w of words) {
      if (!SPELL[w]) continue;
      const prev = it.w.find(x => x.w === w);
      const entry = { w, s: prev ? prev.s : null, r: 'spell', why: (prev && prev.s ? '소리는 [' + prev.s + ']. ' : '') + SPELL[w] };
      if (prev) Object.assign(prev, entry); else it.w.push(entry);
    }
    it.w.forEach(x => { if (x.w === '담요도') x.r = 'change'; });
    return it;
  });
  sql.push(`insert into public.catalog_sets(grade,semester,level_no,title,items,note) values (2,2,${lv},'${title}',$j$${JSON.stringify(items)}$j$::jsonb,'한글, 틀려도 괜찮아! 2-2 단계 · 발음 자동')
on conflict (grade,semester,level_no) do update set title=excluded.title, items=excluded.items, note=excluded.note, updated_at=now();`);
}
